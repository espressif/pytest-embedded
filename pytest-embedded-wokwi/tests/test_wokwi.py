import json
import os
from types import SimpleNamespace

import pytest
from pytest_embedded_wokwi.wokwi import Wokwi, _default_diagram

wokwi_token_required = pytest.mark.skipif(
    not os.getenv('WOKWI_CLI_TOKEN', None),
    reason='Please make sure that `WOKWI_CLI_TOKEN` env var is set. Get a token here: https://wokwi.com/dashboard/ci',
)


def _diagram_resolver(tmp_path, target='esp32s3'):
    app_path = tmp_path / 'app'
    log_path = tmp_path / 'logs' / 'wokwi.log'
    app_path.mkdir()
    log_path.parent.mkdir()
    wokwi = SimpleNamespace(
        app=SimpleNamespace(app_path=str(app_path), target=target),
        _logfile=str(log_path),
    )
    wokwi.create_diagram_json = lambda path=None: Wokwi.create_diagram_json(wokwi, path)
    return wokwi, app_path, log_path.parent


def test_target_specific_diagram_is_preferred(tmp_path):
    wokwi, app_path, _ = _diagram_resolver(tmp_path, 'esp32c6')
    diagram = app_path / 'diagram.esp32c6.json'
    diagram.write_text('{}')

    assert Wokwi._resolve_diagram(wokwi) == str(diagram)


def test_default_diagram_is_generated_outside_app_path(tmp_path):
    wokwi, app_path, log_path = _diagram_resolver(tmp_path)

    diagram_path = Wokwi._resolve_diagram(wokwi)

    assert os.path.dirname(diagram_path) == str(log_path)
    assert not (app_path / 'diagram.json').exists()
    with open(diagram_path) as f:
        generated_diagram = json.load(f)
    assert generated_diagram == _default_diagram('esp32s3')
    assert generated_diagram['author'] == 'Generated by pytest-embedded'


def test_custom_generic_diagram_is_preserved(tmp_path):
    wokwi, app_path, _ = _diagram_resolver(tmp_path)
    diagram = app_path / 'diagram.json'
    custom_diagram = {
        'version': 1,
        'parts': [
            {'type': 'board-esp32-s3-devkitc-1', 'id': 'esp'},
            {'type': 'wokwi-led', 'id': 'led'},
        ],
        'connections': [],
    }
    diagram.write_text(json.dumps(custom_diagram))

    assert Wokwi._resolve_diagram(wokwi) == str(diagram)
    assert json.loads(diagram.read_text()) == custom_diagram


def test_mismatched_custom_diagram_is_preserved_with_warning(tmp_path, caplog):
    wokwi, app_path, _ = _diagram_resolver(tmp_path)
    diagram = app_path / 'diagram.json'
    custom_diagram = {
        'version': 1,
        'parts': [
            {'type': 'board-esp32-devkit-c-v4', 'id': 'esp'},
            {'type': 'wokwi-led', 'id': 'led'},
        ],
        'connections': [],
    }
    diagram.write_text(json.dumps(custom_diagram))

    with caplog.at_level('WARNING'):
        assert Wokwi._resolve_diagram(wokwi) == str(diagram)

    assert 'no part with type "board-esp32-s3-devkitc-1" found' in caplog.text
    assert json.loads(diagram.read_text()) == custom_diagram


def test_legacy_generated_diagram_is_replaced_temporarily_for_target(tmp_path):
    wokwi, app_path, log_path = _diagram_resolver(tmp_path)
    diagram = app_path / 'diagram.json'
    legacy_diagram = _default_diagram('esp32', author='Uri Shaked')
    diagram.write_text(json.dumps(legacy_diagram))

    diagram_path = Wokwi._resolve_diagram(wokwi)

    assert os.path.dirname(diagram_path) == str(log_path)
    assert json.loads(diagram.read_text()) == legacy_diagram
    with open(diagram_path) as f:
        assert json.load(f) == _default_diagram('esp32s3')


def test_create_diagram_json_does_not_overwrite_existing_custom_diagram(tmp_path):
    wokwi, app_path, _ = _diagram_resolver(tmp_path)
    diagram = app_path / 'diagram.json'
    custom_diagram = {'version': 1, 'parts': [], 'connections': []}
    diagram.write_text(json.dumps(custom_diagram))

    Wokwi.create_diagram_json(wokwi)

    assert json.loads(diagram.read_text()) == custom_diagram


@wokwi_token_required
def test_pexpect_by_wokwi_esp32(testdir):
    testdir.makepyfile("""
        import pexpect
        import pytest

        def test_pexpect_by_wokwi(dut):
            dut.expect('Hello world!')
            dut.expect('Restarting')
            with pytest.raises(pexpect.TIMEOUT):
                dut.expect('Hello world! or Restarting not found', timeout=1)
    """)

    result = testdir.runpytest(
        '-s',
        '--embedded-services',
        'idf,wokwi',
        '--app-path',
        os.path.join(testdir.tmpdir, 'hello_world_esp32'),
    )

    result.assert_outcomes(passed=1)


